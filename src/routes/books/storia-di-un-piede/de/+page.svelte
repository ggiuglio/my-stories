        Das Problem ist nicht so sehr das Gewicht: Nach dieser Backpackerreise durch Südostasien bin ich auf alles vorbereitet.
      </p>

      <p class="text-lg leading-relaxed">
        Das Schwierige ist das Fruchtwasser, das auf die Blase drückt, sodass <em>Sie</em> bis zu viermal pro Nacht auf die Toilette muss. Und weil sie eine verliebte Mutter ist, geht sie ohne Licht, um ihn nicht zu wecken, der neben ihr schläft. Und weil man nichts sieht und wir wegen des Bauchs wie eine Ente watscheln, spielen wir seit ein paar Wochen jede Nacht russisches Roulette mit den kleinen Zehen: Sind wir schon beim Schrank? Steht die Tür etwa halb offen?
      </p>

      <p class="text-lg leading-relaxed">
        Aua!! Wer hat den Stuhl verschoben!!
      </p>

      <p class="text-lg leading-relaxed">
        Kurzum, mein armer kleiner Zeh kennt inzwischen jede scharfe Kante auf dem Weg zwischen Bett und Bad.
      </p>

      <p class="text-lg leading-relaxed">
        Auch die Wassereinlagerungen tun ihr Übriges: Diese Riemchenschuhe, die laut <em>Ihr</em> so sehr nach Audrey Hepburn aussehen, sind mir jetzt ein kleines bisschen zu eng.
      </p>

      <p class="text-lg leading-relaxed">
        Aber <em>Sie</em> scheint es nicht zu bemerken, vielleicht weil die neue Vollmondkurve ihres Bauchs mich die meiste Zeit verdeckt.
      </p>

      <p class="text-lg leading-relaxed">
        Also laufen mein Bruder und ich jedes Mal, wenn <em>Sie</em> ihre Freundinnen zum Aperitif trifft, als Würste verkleidet herum.
      </p>

      <p class="text-lg leading-relaxed">
        Aber <em>Sie</em> ist so schön, dass es bestimmt niemandem auffällt.
      </p>

      <p class="text-lg leading-relaxed">
        Was mir aber Sorgen macht, ist etwas anderes: In ein paar Wochen bekommen wir eine Tochter, und dieses kleine Mädchen wird zwei winzige, unerfahrene Füßchen haben.
      </p>

      <p class="text-lg leading-relaxed">
        Und die Kleinen, das weiß man ja, schauen den Großen zu und machen es ihnen nach.
      </p>

      <p class="text-lg leading-relaxed">
        Also muss ich mit gutem Beispiel vorangehen: Schluss damit, die Ferse nachzuziehen, wenn ich müde bin, bloß nicht diesen Anflug von Hammerzeh zeigen, und auf keinen Fall mehr dieses Ding machen, das Gewicht zu sehr auf die Außenseite der Sohle zu legen, wovon uns der Orthopäde, als wir fünfzehn waren, gesagt hat, dass es Skoliose verursachen kann.
      </p>

      <p class="text-lg leading-relaxed">
        Und wenn wir sie dann auf dem Arm tragen, muss ich ganz besonders auf Stufen, nassen Marmor und Glatteis im Winter aufpassen.
      </p>

      <p class="text-lg leading-relaxed">
        Und wenn sie größer ist, muss ich ihr zeigen, wie man elegant auf hohen Absätzen läuft, ohne Blasen so groß wie Zitronen zu bekommen...
      </p>

      <p class="text-lg leading-relaxed">
        Je mehr ich darüber nachdenke, desto länger wird die Liste der Verantwortungen, und das alles für mindestens sechzehn Jahre, sogar länger, wenn sie nach der Kleinen noch mehr Kinder haben wollen.
      </p>

      <p class="text-lg leading-relaxed">
        Genug, um selbst dem mutigsten aller Füße die Nägel zittern zu lassen.
      </p>

      <p class="text-lg leading-relaxed">
        Ich lasse mich von dieser Welle von Gedanken überrollen und warte geduldig auf die Ebbe.
      </p>

      <p class="text-lg leading-relaxed">
        Ich habe keine Eile, als Fuß muss ich nicht dringend atmen.
      </p>

      <p class="text-lg leading-relaxed">
        Ich kann mir Zeit lassen.
      </p>

      <p class="text-lg leading-relaxed">
        Als sich alle Sorgen endlich zurückziehen, ist meine Stimmung eine ganz andere: Ich bin begeistert.
      </p>

      <p class="text-lg leading-relaxed">
        Ein Fuß.
      </p>

      <p class="text-lg leading-relaxed">
        Genau wie ich.
      </p>

      <p class="text-lg leading-relaxed">
        Aber mit etwas vom wunderschönen Fuß ihres Vaters, was wird er wohl von ihm haben?
      </p>

      <p class="text-lg leading-relaxed">
        Hoffentlich nicht diese schönen lockigen Haare am Knöchel, die wären bei einem kleinen Mädchen ein bisschen seltsam.
      </p>

      <p class="text-lg leading-relaxed">
        Ich kann es kaum erwarten, den Fuß unserer Tochter kennenzulernen.
      </p>

      <p class="text-lg leading-relaxed">
        Und ich kann es kaum erwarten, ihm alles zu zeigen, was ich in diesen Jahren gelernt habe: wie man einen Fußball im Flug stoppt, damit die Jungs in der Schule neidisch werden; wie man mit dem Spann leicht über die linke Wade streicht, wenn <em>Sie</em> einen Rock trägt und die Diva spielen will; wie man den großen Zeh anhebt, damit die Flip-Flops beim Rennen am Strand nicht davonfliegen; wie man sich in Skischuhen anspannt und wieder entspannt, um sich im Sessellift keine Frostbeulen zu holen... Ich habe Tausende Tricks, die ich ihm beibringen kann.
      </p>

      <p class="text-lg leading-relaxed">
        Aber vor allem bin ich gespannt auf seine Tricks: Wird er sich auf den Zehenspitzen drehen können und aus der Kleinen eine Ballerina machen? Oder wird er das Wasser wegdrücken können wie ein Entenfuß und aus ihr eine Schwimmerin machen?
      </p>

      <p class="text-lg leading-relaxed">
        Wird er kitzelig sein wie ich?
      </p>

      <p class="text-lg leading-relaxed">
        Oder leicht frieren wie die Füße ihres Vaters?
      </p>

      <p class="text-lg leading-relaxed">
        Was auch immer es sein wird, es wird ein wunderschönes Abenteuer, und ich bin bereit dafür.
      </p>

      <h2 class="chapter-title">Kapitel VI</h2>

      <p class="text-lg leading-relaxed">
        Es ist seltsam, alt zu sein: Man kann fast nichts mehr tun, aber gleichzeitig ist es einem egal.
      </p>

      <p class="text-lg leading-relaxed">
        Wäre meine Plantarfaszie mit achtzehn so steif gewesen, dass schon der Gedanke, auch nur eine einzige Stufe hinunterzuspringen, reine Science-Fiction gewesen wäre, wäre ich verzweifelt.
      </p>

      <p class="text-lg leading-relaxed">
        Jetzt aber ist es gut so. Mit dem Alter sind alle Tätigkeiten des Körpers unwichtiger geworden, selbst die grundlegenden wie Essen und Atmen werden als Routine erledigt, ohne die Begeisterung und den Eifer von früher.
      </p>

      <p class="text-lg leading-relaxed">
        Es muss vierzig Jahre her sein, dass <em>Sie</em> zuletzt ausprobiert hat, ob sie hoch genug springen kann, um diese Lampe zu berühren, und mindestens zwanzig, dass sie versucht hat, mich hinter den Kopf zu legen (wofür ihr meine Freundin, die Hüfte, sehr dankbar ist).
      </p>

      <p class="text-lg leading-relaxed">
        Mangels besonderer körperlicher Betätigung konzentriere ich mich auf die Empfindungen. Obwohl meine Haut jetzt hart und runzlig ist wie die eines Elefanten, fühle ich viel besser als in unserer Jugend.
      </p>

      <p class="text-lg leading-relaxed">
        Mit den Jahren habe ich entdeckt, dass man nicht mit der Haut fühlt und auch nicht mit den Nerven, sondern mit den Erinnerungen.
      </p>

      <p class="text-lg leading-relaxed">
        Die ersten Empfindungen, die ich gesammelt habe, als wir ein Baby waren, das in der Windel versuchte, sich in die Füße zu beißen, waren einfach, fast mechanisch, ohne Nuancen.
      </p>

      <p class="text-lg leading-relaxed">
        Warm, kalt, hart, weich, ohne Erinnerungen und ohne Vergleichsmaßstab, nichts als reine Dienstinformationen, kalt wie die Berechnungen eines Ingenieurs: Mir ist kalt, zieht mir Socken an.
      </p>

      <p class="text-lg leading-relaxed">
        Jetzt dagegen, mit den Millionen vergangener Empfindungen, die sich in unserem Nervensystem angesammelt haben, ist alles ein Spiel der Verweise.
      </p>

      <p class="text-lg leading-relaxed">
        Das Gehirn und ich spielen dieses Spiel stundenlang, ohne uns je zu langweilen.
      </p>

      <p class="text-lg leading-relaxed">
        Zum Beispiel haben sie mir gerade die Socke ausgezogen und ich liege auf meinem Lieblingsschemel neben der Heizung.
      </p>

      <p class="text-lg leading-relaxed">
        Das Gefühl an meiner Sohle erinnert mich daran, wie es war, über den rauen Holzboden des Hauses in den Bergen zu laufen.
      </p>

      <p class="text-lg leading-relaxed">
        Ich schicke es ans Gehirn, und es antwortet sofort mit Erinnerungen an einen Urlaub. Es war der Sommer, in dem unsere Kleine geboren wurde, es war zu heiß, um mit diesem riesigen Bauch am Meer zu sein, und so waren wir in die Berge gefahren.
      </p>

      <p class="text-lg leading-relaxed">
        Jetzt hat jemand das Fenster geöffnet und ein kalter Luftzug erfasst mich, ein Schauer überläuft mich wie damals, wenn einem Schnee in die Schuhe kommt. Und prompt antwortet das Gehirn mit Erinnerungen an die Zeit im Trentino, als wir dem Kleinen das Skifahren beibrachten.
      </p>

      <p class="text-lg leading-relaxed">
        Es ist mein Lieblingsspiel, ich werde es nie müde.
      </p>

      <h2 class="chapter-title">Kapitel VII</h2>

      <p class="text-lg leading-relaxed">
        Wir sind jetzt schon eine Weile hier: auf diesem kleinen, unbequemen weißen Bett im selben Krankenhaus, in dem wir geboren wurden. Um uns herum ist die ganze Familie, aber niemand sagt etwas.
      </p>

      <p class="text-lg leading-relaxed">
        Auch <em>Sie</em> spricht seit ein paar Stunden nicht mehr; vielleicht ist sie wach, vielleicht schläft sie, selbst ich kann von meinem privilegierten Platz aus den Unterschied kaum noch erkennen.
      </p>

      <p class="text-lg leading-relaxed">
        Das Ende naht, ich weiß es, aber ich habe keine Angst. Ich kann an nichts anderes denken als an den Fuß der Kleinen. Sie sitzt auf dem Arm ihrer Mutter, die einmal unsere Kleine war, und ihr winziger rosa Fuß schwingt hin und her wie das Metronom, das in den Klavierstunden den Takt schlug: tick-tack, tick-tack, tick-tack...
      </p>

      <p class="text-lg leading-relaxed">
        Alles scheint sich dem Rhythmus dieses kleinen Fußes anzupassen und langsamer zu werden, und auf einmal tauchen Erinnerungen auf, von denen ich nicht wusste, dass ich sie habe.
      </p>

      <p class="text-lg leading-relaxed">
        Wir sind wieder in Mamas Bauch, aber jetzt läuft die Zeit rückwärts.
      </p>

      <p class="text-lg leading-relaxed">
        Es ist, als würde der Film meiner Geschichte zurückgespult.
      </p>

      <p class="text-lg leading-relaxed">
        Ich spüre, wie sich der komplizierte Vorgang, der aus einer Zelle ein Mädchen und dann eine Frau gemacht hat, zurückzieht wie eine lange Ebbe.
      </p>

      <p class="text-lg leading-relaxed">
        Die Nägel verschwinden, die Knochen werden immer weniger deutlich, die Zehen wachsen zusammen, die Blutgefäße und Nerven ziehen sich zurück: Die perfekte Laufmaschine, die ich war, schrumpft zu einem Haufen undifferenzierter Zellen und am Ende, zusammen mit dem ganzen Rest des Körpers, zu einer einzigen.
      </p>

      <p class="text-lg leading-relaxed">
        Für einen Moment.
      </p>

      <p class="text-lg leading-relaxed">
        Und dann ist Schluss.
      </p>

      <p class="text-lg leading-relaxed">
        Nichts mehr.
      </p>

