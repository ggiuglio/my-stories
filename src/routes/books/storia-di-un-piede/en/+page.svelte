      </p>

      <p class="text-lg leading-relaxed">
        Hot, cold, hard, soft, with no memories and nothing to compare them to, they were just plain service information, as cold as an engineer's calculations: I'm cold, put my socks on.
      </p>

      <p class="text-lg leading-relaxed">
        Now, with millions of past sensations stored in our nervous system, everything is a game of echoes.
      </p>

      <p class="text-lg leading-relaxed">
        The brain and I play this game for hours without ever getting bored.
      </p>

      <p class="text-lg leading-relaxed">
        For example, they've just taken my sock off and I'm resting on my favourite footstool, next to the radiator.
      </p>

      <p class="text-lg leading-relaxed">
        The feeling on my sole reminds me of walking on the rough wooden floor of the house in the mountains.
      </p>

      <p class="text-lg leading-relaxed">
        I send it to the brain and it immediately answers with memories of a holiday. It was the summer our little girl was born, it was too hot to be at the seaside with that huge belly, so we'd gone to the mountains.
      </p>

      <p class="text-lg leading-relaxed">
        Now someone has opened the window and a cold draught hits me, giving me a shiver like when snow gets into your shoes. And right on cue the brain answers with memories of when we were in Trentino teaching our little boy to ski.
      </p>

      <p class="text-lg leading-relaxed">
        It's my favourite game, I never get tired of it.
      </p>

      <h2 class="chapter-title">Chapter VII</h2>

      <p class="text-lg leading-relaxed">
        We've been here for a while now: on this small, uncomfortable white bed in the same hospital where we were born. The whole family is around us, but nobody says anything.
      </p>

      <p class="text-lg leading-relaxed">
        <em>She</em> hasn't spoken for a few hours either; maybe she's awake, maybe she's asleep, even I, from my privileged position, can barely tell the difference any more.
      </p>

      <p class="text-lg leading-relaxed">
        The end is coming, I know, but I'm not afraid. All I can think about is the little one's foot. She's in her mother's arms, the one who was once our little girl, and her tiny pink foot swings back and forth like the metronome that kept time during piano lessons: tick-tock, tick-tock, tick-tock...
      </p>

      <p class="text-lg leading-relaxed">
        Everything seems to slow down to the rhythm of that little foot, and all of a sudden memories I didn't know I had come floating up.
      </p>

      <p class="text-lg leading-relaxed">
        We're back in Mum's belly, but now time is running backwards.
      </p>

      <p class="text-lg leading-relaxed">
        It's as if the film of my story were rewinding.
      </p>

      <p class="text-lg leading-relaxed">
        I feel the complicated process that turned a cell into a little girl, and then a woman, drawing back like a long ebbing tide.
      </p>

      <p class="text-lg leading-relaxed">
        The nails disappear, the bones grow less and less defined, the toes fuse together, the blood vessels and nerves withdraw: that perfect running machine I once was shrinks to a cluster of undifferentiated cells, and in the end, together with the rest of the body, to just one.
      </p>

      <p class="text-lg leading-relaxed">
        For a moment.
      </p>

      <p class="text-lg leading-relaxed">
        And then that's it.
      </p>

      <p class="text-lg leading-relaxed">
        Nothing more.
      </p>

      <p class="text-lg leading-relaxed">
        <em>The End</em>
      </p>
