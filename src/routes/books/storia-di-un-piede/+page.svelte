        In breve il mio povero mignolo ha scoperto la posizione di tutti gli spigoli vivi che adornano la via tra il letto e il bagno.
      </p>

      <p class="text-lg leading-relaxed">
        Anche la ritenzione idrica fa la sua parte: quelle scarpe coi laccetti che secondo <em>Lei</em> fanno tanto Audrey Hepburn adesso mi vanno un tantino strette.
      </p>

      <p class="text-lg leading-relaxed">
        Ma <em>Lei</em> non sembra accorgersene, forse perché la nuova curva della pancia di luna piena mi nasconde per la maggior parte del tempo.
      </p>

      <p class="text-lg leading-relaxed">
        Così ogni volta che <em>Lei</em> incontra le amiche per l'aperitivo io e mio fratello andiamo in giro travestiti da insaccati.
      </p>

      <p class="text-lg leading-relaxed">
        Ma <em>Lei</em> è così bella che sono sicuro non se ne accorga nessuno.
      </p>

      <p class="text-lg leading-relaxed">
        La cosa che mi preoccupa però è un'altra: tra qualche settimana avremo una figlia, e questa bambina avrà due piccoli piedini inesperti.
      </p>

      <p class="text-lg leading-relaxed">
        E i piccoli, si sa, guardano gli adulti e li imitano.
      </p>

      <p class="text-lg leading-relaxed">
        Allora sarò io a dover dare il buon esempio: basta trascinare il tallone quando sono stanco, guai a mostrare quell'accenno di dito a martello e assolutamente non fare mai più quella cosa di mettere il peso troppo sull'esterno della pianta che l'ortopedico quando avevamo quindici anni ci ha detto che poteva far venire la scoliosi.
      </p>

      <p class="text-lg leading-relaxed">
        E poi quando la avremo in braccio dovrò stare super attento ai gradini, al marmo bagnato e alle lastre di ghiaccio d'inverno.
      </p>

      <p class="text-lg leading-relaxed">
        E quando sarà più grande dovrò farle vedere come si cammina con eleganza su un tacco alto senza farsi venire delle vesciche grosse come limoni...
      </p>

      <p class="text-lg leading-relaxed">
        Più ci penso e più la lista delle responsabilità cresce, e tutto questo per un minimo di sedici anni, anche di più se dopo la Piccola decidono di avere altri figli.
      </p>

      <p class="text-lg leading-relaxed">
        Roba da fare tremare le unghie anche al più coraggioso dei piedi.
      </p>

      <p class="text-lg leading-relaxed">
        Lascio che quest'onda di pensieri mi sommerga e aspetto pazientemente la risacca.
      </p>

      <p class="text-lg leading-relaxed">
        Non ho fretta, essendo un piede non ho l'urgenza di respirare.
      </p>

      <p class="text-lg leading-relaxed">
        Posso prendermela comoda.
      </p>

      <p class="text-lg leading-relaxed">
        Quando tutte le preoccupazioni finalmente si ritirano il mio stato d'animo è completamente diverso: sono entusiasta.
      </p>

      <p class="text-lg leading-relaxed">
        Un piede.
      </p>

      <p class="text-lg leading-relaxed">
        Proprio come me.
      </p>

      <p class="text-lg leading-relaxed">
        Ma con qualcosa del bellissimo piede di suo padre, cosa prenderà da lui?
      </p>

      <p class="text-lg leading-relaxed">
        Speriamo non quei bei peli ricci sulla caviglia, sarebbero un po' strani per una bambina.
      </p>

      <p class="text-lg leading-relaxed">
        Non vedo l'ora di conoscere il piede di nostra figlia.
      </p>

      <p class="text-lg leading-relaxed">
        E non vedo l'ora di mostrargli tutto quello che ho imparato in questi anni: come bloccare al volo un pallone da calcio per fare invidia ai maschi a scuola, come strofinare leggermente il mio dorso sul polpaccio sinistro quando <em>Lei</em> porta la gonna e vuole fare la diva, come tirare su l'alluce per non fare volare via le infradito quando corriamo in spiaggia, come contrarsi e rilassarsi negli scarponi da sci per non farsi venire i geloni in seggiovia... ho migliaia di trucchi da insegnargli.
      </p>

      <p class="text-lg leading-relaxed">
        Ma più di tutto sono impaziente di vedere i suoi trucchi: saprà roteare sulle punte e farà della Piccola una ballerina? O saprà spingere l'acqua come la zampa di una papera e ne farà una nuotatrice?
      </p>

      <p class="text-lg leading-relaxed">
        Soffrirà il solletico come me?
      </p>

      <p class="text-lg leading-relaxed">
        O il freddo come i piedi di suo padre?
      </p>

      <p class="text-lg leading-relaxed">
        Qualsiasi cosa sarà, sarà un'avventura bellissima e io sono pronto per affrontarla.
      </p>

      <h2 class="chapter-title">Capitolo VI</h2>

      <p class="text-lg leading-relaxed">
        È strano essere vecchi: non riesci a fare più quasi nulla, ma al tempo stesso non ti importa.
      </p>

      <p class="text-lg leading-relaxed">
        Se a diciotto anni la mia fascia plantare fosse stata così rigida da far diventare pura fantascienza l'idea di saltare anche solo uno scalino mi sarei disperato.
      </p>

      <p class="text-lg leading-relaxed">
        Ora invece va bene così. Con l'età che avanza tutte le attività del corpo sono diventate meno importanti, anche quelle fondamentali come mangiare e respirare vengono portate avanti come una routine, senza l'entusiasmo e la foga di una volta.
      </p>

      <p class="text-lg leading-relaxed">
        Saranno quarant'anni che <em>Lei</em> non prova più a vedere se riesce a saltare abbastanza in alto per toccare quella lampada e almeno venti che non prova a mettermi dietro la testa (di questo le è molto grata la mia amica anca).
      </p>

      <p class="text-lg leading-relaxed">
        In mancanza di particolari attività motorie mi concentro sulle sensazioni. Anche se la mia pelle ora è dura e rugosa come quella di elefante sento molto meglio di quando eravamo giovani.
      </p>

      <p class="text-lg leading-relaxed">
        Negli anni ho scoperto che non si sente con la pelle, né con i nervi, ma con i ricordi.
      </p>

      <p class="text-lg leading-relaxed">
        Le prime sensazioni che ho raccolto, quando eravamo un bebè che cercava di mordersi i piedi nel pannolino erano semplici, quasi meccaniche, senza sfumature.
      </p>

      <p class="text-lg leading-relaxed">
        Caldo, freddo, duro, morbido, senza ricordi e senza un metro di paragone, sono solo pure informazioni di servizio, fredde come i calcoli di un ingegnere: ho freddo, mettetemi le calze.
      </p>

      <p class="text-lg leading-relaxed">
        Ora invece con i milioni di sensazioni passate accumulate nel nostro sistema nervoso ogni cosa è un gioco di rimandi.
      </p>

      <p class="text-lg leading-relaxed">
        Io e il cervello giochiamo questo gioco per ore, senza annoiarci mai.
      </p>

      <p class="text-lg leading-relaxed">
        Per esempio, ora mi hanno tolto la calza e sono appoggiato sul mio sgabello preferito, di fianco al termosifone.
      </p>

      <p class="text-lg leading-relaxed">
        La sensazione che provo sulla pianta mi ricorda quella di camminare sul pavimento di legno ruvido della casa in montagna.
      </p>

      <p class="text-lg leading-relaxed">
        La mando al cervello e lui subito mi risponde con dei ricordi di una vacanza. Era l'estate in cui è nata la nostra piccola, faceva troppo caldo per stare al mare con quella panciona e così eravamo andati in montagna.
      </p>

      <p class="text-lg leading-relaxed">
        Adesso qualcuno ha aperto la finestra e uno spiffero freddo mi investe, mi prende un brivido come quando ti entra la neve nelle scarpe. E prontamente il cervello mi risponde con i ricordi di quando eravamo in Trentino e insegnavamo al piccolo a sciare.
      </p>

      <p class="text-lg leading-relaxed">
        È il mio gioco preferito, non mi stanco mai.
      </p>

      <h2 class="chapter-title">Capitolo VII</h2>

      <p class="text-lg leading-relaxed">
        Siamo qui ormai da un po': su questo piccolo scomodo letto bianco nello stesso ospedale in cui siamo nati. Attorno a noi c'è tutta la famiglia, ma nessuno dice niente.
      </p>

      <p class="text-lg leading-relaxed">
        Anche <em>Lei</em> non parla più da qualche ora forse è sveglia, forse dorme, persino io dalla mia posizione privilegiata ormai faccio fatica a distinguere la differenza.
      </p>

      <p class="text-lg leading-relaxed">
        Sta arrivando la fine, lo so ma non sono spaventato. Tutto quello a cui riesco a pensare è il piede della piccolina. Lei sta in braccio alla mamma, quella che una volta era la nostra piccolina, e il suo piccolo piede rosa oscilla avanti e indietro come il metronomo che scandiva il tempo nelle lezioni di pianoforte: tic-tac, tic-tac, tic-tac...
      </p>

      <p class="text-lg leading-relaxed">
        Tutto sembra rallentare al ritmo di quel piccolo piede e a un tratto tornano a galla ricordi che non sapevo di avere.
      </p>

      <p class="text-lg leading-relaxed">
        Siamo di nuovo nella pancia della mamma ma il tempo ora scorre al contrario.
      </p>

      <p class="text-lg leading-relaxed">
        È come se la pellicola della mia storia si stesse riavvolgendo.
      </p>

      <p class="text-lg leading-relaxed">
        Sento il complicato processo che ha portato una cellula a diventare una bambina, e poi una donna, ritirarsi come una lunga risacca.
      </p>

      <p class="text-lg leading-relaxed">
        Spariscono le unghie, le ossa diventano sempre meno definite, le dita si incollano assieme, i vasi sanguinei e i nervi si ritirano: quella perfetta macchina per correre che ero si riduce a un gruppo di cellule indistinte, e alla fine, insieme a tutto il resto del corpo, a una sola.
      </p>

      <p class="text-lg leading-relaxed">
        Per un momento.
      </p>

      <p class="text-lg leading-relaxed">
        E poi basta.
      </p>

      <p class="text-lg leading-relaxed">
        Più niente.
      </p>

      <p class="text-lg leading-relaxed">
        <em>Fine</em>
      </p>
