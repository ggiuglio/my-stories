      <h2>Die Band</h2>

      <p class="text-lg leading-relaxed">
        Es gibt sicher viele Archetypen des Funk-Jazz-Musikers; bisher habe ich drei identifiziert.
      </p>

      <h3>Der Schlagzeuger im amerikanischen College-Stil</h3>

      <p class="text-lg leading-relaxed">
        Er trägt ein offenes Hemd über einem einfarbigen T-Shirt, den obligatorischen Bart, Brille und Baseballkappe. Zufälligerweise ist das auch der Lieblingslook des Systemadministrators in jedem beliebigen Berliner Start-up. Die beiden Menschentypen sind praktisch nicht voneinander zu unterscheiden, bis der Schlagzeuger zu den Sticks greift (oder versucht, dir den Mailserver einzurichten).
      </p>

      <h3>Der Hipster-Gitarrist</h3>

      <p class="text-lg leading-relaxed">
        Inzwischen ein zeitloser Klassiker wie Apple Pie in Amerika: Jeanshemd bis zum obersten Knopf zugeknöpft, weiße Sneaker und Achtziger-Jahre-Schnauzer. In den Bars von Friedrichshain ist diese Art häufiger anzutreffen als Sturmtruppler auf dem Todesstern.
      </p>

      <h3>Der intellektuelle Keyboarder</h3>

      <p class="text-lg leading-relaxed">
        Der Stil des deutschen Intellektuellen ist leicht zu erkennen und klar von dem des südeuropäischen oder franko-britischen Intellektuellen abzugrenzen. Er beruht auf zwei unverzichtbaren Accessoires: der kleinen runden Brille (man könnte sie Harry-Potter-Brille nennen, aber korrekter wäre es zu sagen, dass Rowling ihrem kleinen Zauberer die Brille eines vierzigjährigen deutschen Intellektuellen verpasst hat) und dem Fischerhut.
      </p>

      <p class="text-lg leading-relaxed">
        Diese seltsame Kopfbedeckung, an den Flussufern ganz Europas weit verbreitet, hatte im Lauf der Jahre vereinzelte Auftritte in Popvideos auf MTV und in den Kleiderschränken einiger Teenager, die wirklich nicht wussten, was sie anziehen sollten. Ihre eigentliche ökologische Nische sind aber Debatten über armenische Philosophie und vegane Ägyptologie in den Kellern Ostberlins: Hier gedeiht sie auch außerhalb der Angelsaison und entwickelt sich in verschiedenste Stoffe und Farben weiter, bereit, jedes Jahr mit der Rückkehr der Karpfen wieder aufzutauchen.
      </p>

      <h2>Das Publikum</h2>

      <p class="text-lg leading-relaxed">
        Wenn schon die Band Stoff für Studien zur menschlichen Verhaltensforschung bot, ist das Publikum eine echte Goldgrube. Das besondere Habitat Jazzclub bringt verschiedene Menschenarten, die normalerweise streng voneinander getrennt leben, dazu, sich einen ziemlich engen Lebensraum zu teilen, und ist damit eine hervorragende Gelegenheit, ihre unterschiedlichen Merkmale und möglichen Wechselwirkungen zu studieren.
      </p>

      <p class="text-lg leading-relaxed">
        Hier ein paar Arten, die mir an einem einzigen Beobachtungsabend aufgefallen sind.
