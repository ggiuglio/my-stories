      <h2>Sonata in Do maggiore "La cagata"</h2>
      
      <h3>Overture &mdash; <em>allegretto</em></h3>
      
      <p class="text-lg leading-relaxed">
        Nel letto: un leggero crepitio di flauti e triangolo risveglia i sensi.
      </p>
      
      <p class="text-lg leading-relaxed">
        L'oboe in lontananza annuncia l'avvicinarsi della tempesta.
      </p>
      
      <h3>Esposizione &mdash; <em>andante grazioso</em></h3>
      
      <p class="text-lg leading-relaxed">
        A pannolino ben allacciato, fagotto e contro-fagotto dettano il ritmo del finale della digestione. Gli archi, guidati dalla viola, disegnano nell'aria arabeschi sensoriali.
      </p>
      
      <h3>Sviluppo &mdash; <em>crescendo sforzato</em></h3>
      
      <p class="text-lg leading-relaxed">
        I fiati (cominciando pianissimo) creano un'atmosfera interrogativa.
      </p>
      
      <p class="text-lg leading-relaxed">
        Mentre il pannolino si apre, il contrabbasso e grandi colpi di timpano ci avvisano della tragedia imminente.
      </p>
      
      <p class="text-lg leading-relaxed">
        Crescendo sempre più, la fuga del primo violino e il contrappunto del violoncello illustrano il sempiterno inseguimento del culo che spara e del papà che para col pannolino.
      </p>
      
      <p class="text-lg leading-relaxed">
        Note di cembalo, fresche come l'acqua corrente, chiudono il movimento.
      </p>
      
      <h3>Ripresa &mdash; <em>allegretto scherzoso</em></h3>
      
      <p class="text-lg leading-relaxed">
        Un'armonia di fiati, guidata dalla tuba, ci ricorda la calma morbidezza di un asciugamano di cotone su una chiappa umida.
      </p>
      
      <p class="text-lg leading-relaxed">
